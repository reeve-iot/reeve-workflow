import { expect, test } from './support/fixtures'
import { dropPaletteBlock, NODE_HEADER_POINT } from './support/canvas'
import { createWorkflow } from './support/nodes'
import { clearSelection } from './support/reeve-ported'

test('a block dropped at the canvas right edge stays visible beside its configuration panel', async ({ page, harness }) => {
  const name = `Drop placement ${String(Date.now())}`
  await createWorkflow(page, name, harness)
  const canvas = page.getByTestId('workflow-canvas')
  await expect(canvas).toBeVisible()
  const canvasBounds = await canvas.boundingBox()
  if (canvasBounds === null) throw new Error('Canvas has no bounding box.')
  await dropPaletteBlock(page, 'WaitForDuration', 'Control Flow', { x: canvasBounds.width - 8, y: 160 })
  const node = page.getByTestId('workflow-node-WaitForDuration')
  await expect(node).toHaveCount(1)
  const nodeId = await node.getAttribute('data-node-id')
  if (nodeId === null) throw new Error('Dropped node has no id.')
  const nodeBody = page.getByTestId(`workflow-node-body-${nodeId}`)
  const outputPort = page.locator(`[data-testid^="workflow-port-${nodeId}-output-"]`).first()
  const panel = page.getByTestId('node-config-panel')
  await expect(panel).toBeVisible()
  await clearSelection(page)
  await nodeBody.click({ position: NODE_HEADER_POINT })
  await expect(panel).toBeVisible()
  const bodyBounds = await nodeBody.boundingBox()
  const panelBounds = await panel.boundingBox()
  if (bodyBounds === null || panelBounds === null) throw new Error('Node or configuration panel has no bounding box.')
  expect(bodyBounds.x + bodyBounds.width).toBeLessThanOrEqual(panelBounds.x)
  const portBounds = await outputPort.boundingBox()
  if (portBounds === null) throw new Error('Output port has no bounding box.')
  expect(portBounds.x + portBounds.width).toBeLessThanOrEqual(panelBounds.x)
  await outputPort.hover()
  await page.mouse.down()
  await page.mouse.move(portBounds.x + portBounds.width / 2 + 4, portBounds.y + portBounds.height / 2 + 4)
  await expect(page.locator('svg line[stroke-dasharray="5,5"]')).toBeVisible()
  await page.mouse.up()
  await expect(nodeBody).toBeVisible()
})

test('consecutive right-edge drops keep both nodes and output ports before the panel', async ({ page, harness }) => {
  const name = `Repeated drop placement ${String(Date.now())}`
  await createWorkflow(page, name, harness)
  const canvas = page.getByTestId('workflow-canvas')
  await expect(canvas).toBeVisible()
  const bounds = await canvas.boundingBox()
  if (bounds === null) throw new Error('Canvas has no bounding box.')
  await dropPaletteBlock(page, 'WaitForDuration', 'Control Flow', { x: bounds.width - 8, y: 160 })
  const panel = page.getByTestId('node-config-panel')
  await expect(panel).toBeVisible()
  const first = page.getByTestId('workflow-node-WaitForDuration').first()
  const narrowed = await canvas.boundingBox()
  if (narrowed === null) throw new Error('Canvas has no bounding box.')
  await dropPaletteBlock(page, 'WaitForDuration', 'Control Flow', { x: narrowed.width - 8, y: 160 })
  const nodes = page.getByTestId('workflow-node-WaitForDuration')
  await expect(nodes).toHaveCount(2)
  const panelBounds = await panel.boundingBox()
  if (panelBounds === null) throw new Error('Panel has no bounding box.')
  for (let index = 0; index < 2; index += 1) {
    const node = nodes.nth(index)
    const body = node.locator('[data-testid^="workflow-node-body-"]')
    const bodyBounds = await body.boundingBox()
    const nodeId = await node.getAttribute('data-node-id')
    if (bodyBounds === null || nodeId === null) throw new Error('Node has no geometry or id.')
    expect(bodyBounds.x + bodyBounds.width).toBeLessThanOrEqual(panelBounds.x)
    const portBounds = await page.locator(`[data-testid^="workflow-port-${nodeId}-output-"]`).first().boundingBox()
    if (portBounds === null) throw new Error('Output port has no bounding box.')
    expect(portBounds.x + portBounds.width).toBeLessThanOrEqual(panelBounds.x)
  }
  await expect(first).toBeVisible()
})
