test('checkpoint controls reject malformed policy forms and preserve the last good value @row:workflow-row.CheckpointPolicyJson#malformed', async ({ page, harness }) => {
  const name = await createWorkflow(page, harness.pageUrl, 'Prevent malformed checkpoint policy')
  await openWorkflowSettings(page)
  const dialog = page.getByRole('dialog', { name: 'Workflow settings' })
  await dialog.getByRole('tab', { name: 'Concurrency' }).click()
  const mode = dialog.getByRole('combobox', { name: 'Checkpoint policy mode' })
  await mode.click()
  const modes = (await page.getByRole('option').allTextContents()).map((text) => text.trim())
  expect(modes).toEqual(['None — the engine decides', 'Every block', 'Before non-idempotent blocks only', 'Heartbeat'])
  await page.getByRole('option', { name: 'Every block', exact: true }).click()
  await mode.click()
  await page.getByRole('option', { name: 'Heartbeat', exact: true }).click()
  const seconds = dialog.getByRole('textbox', { name: 'Checkpoint heartbeat seconds' })
  await seconds.fill('0')
  await seconds.press('Enter')
  await expect(page.getByText(/Must be 1 or more/)).toBeVisible()
  await dialog.getByRole('button', { name: 'Done' }).click()
  await saveWorkflowRequest(page)
  const summary = (await harness.api.getWorkflows()).find((workflow) => workflow.name === name)
  if (summary === undefined) throw new Error(`Workflow '${name}' is missing from the stored list.`)
  const stored = await harness.api.getWorkflow({ id: summary.id })
  expect(JSON.parse(stored.checkpointPolicyJson ?? 'null')).toEqual({ Mode: 'EveryBlock' })
})

test('the literal JSON editor refuses null and stores no null mapping @row:port-type-unresolved', async ({ page, harness }) => {
  const name = await createWorkflow(page, harness.pageUrl, 'Prevent unresolved literal type')
  await dropBlock(page, 'Filter', 'Control Flow', { x: 0.4, y: 0.35 })
  const filterId = await page.getByTestId('workflow-node-Filter').getAttribute('data-node-id')
  if (filterId === null) throw new Error('The Filter node has no id.')
  await drawWire(
    page,
    page.getByTestId('workflow-port-__workflow_input__-output-__start__'),
    page.getByTestId(`workflow-port-${filterId}-input-Collection`),
  )
  await page.getByRole('combobox', { name: 'Collection mapping type' }).click()
  await page.getByRole('option', { name: 'Literal', exact: true }).click()
  await page.getByRole('textbox', { name: 'Collection literal' }).fill('null')
  await expect(page.getByText('null is not a literal value; use an expression instead')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Save Mappings' })).toBeDisabled()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await saveWorkflowRequest(page)
  const stored = await latestVersionForName(harness, name)
  const definition = readStoredDefinitionText(stored.definitionJson)
  if (!definition.ok) throw new Error(`Stored definition unreadable: ${JSON.stringify(definition.fault)}`)
  const edge = definition.definition.edges.find((item) => item.targetNodeId === filterId)
  expect(edge?.mappings).toEqual({})
})

