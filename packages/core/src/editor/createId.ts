/** Default id source for new nodes and edges. `crypto.randomUUID` is absent outside a secure context and
 * in several test environments, so it is used when present and otherwise built from random bytes. Ids only
 * have to be unique within one document, and a host that needs its own scheme passes `createId`. */
export function createDefaultId(): string {
  const webCrypto: Crypto | undefined = typeof globalThis === 'undefined' ? undefined : globalThis.crypto
  if (typeof webCrypto?.randomUUID === 'function') return webCrypto.randomUUID()

  const bytes = new Uint8Array(16)
  if (typeof webCrypto?.getRandomValues === 'function') {
    webCrypto.getRandomValues(bytes)
  } else {
    for (let i = 0; i < bytes.length; i += 1) bytes[i] = Math.floor(Math.random() * 256)
  }
  bytes[6] = ((bytes[6] ?? 0) & 0x0f) | 0x40
  bytes[8] = ((bytes[8] ?? 0) & 0x3f) | 0x80

  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}
