import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { describe, expect, it } from 'vitest'
import type { BlockTypeDescriptor } from '../model/blockType.js'
import type { ValidationFinding, VariableMapping, WorkflowDefinition, WorkflowEdge, WorkflowNode } from '../model/workflow.js'
import { BUILTIN_PORT_TYPES } from '../portTypes/builtins.js'
import { createPortTypeRegistry } from '../portTypes/registry.js'
import { createWorkflowEditorStore } from './store.js'

type Depth = 'root' | 'body' | 'nested'
type Missing = 'source' | 'target' | 'both'
type Mapping = 'none' | 'literal' | 'direct'
interface Spec { depth: Depth; missing: Missing; mapping: Mapping }
interface Case { name: string; definition: WorkflowDefinition; expect: string[] }
interface BlockRow { blockTypeId: string; displayName: string; requiredStringInputs: string[]; stringOutputs: string[]; subCanvases: string[] }

const DEPTHS: readonly Depth[] = ['root', 'body', 'nested']
const MISSING: readonly Missing[] = ['source', 'target', 'both']
const MAPPINGS: readonly Mapping[] = ['none', 'literal', 'direct']
const INPUT = '__workflow_input__'

const BLOCKS: BlockRow[] = [
  { blockTypeId: 'notify', displayName: 'Notify', requiredStringInputs: ['Message'], stringOutputs: ['Text'], subCanvases: [] },
  { blockTypeId: 'loop.for', displayName: 'For Loop', requiredStringInputs: [], stringOutputs: [], subCanvases: ['Body'] },
]

const node = (id: string, blockTypeId: string, configuration: WorkflowNode['configuration'] = {}): WorkflowNode =>
  ({ id, blockTypeId, position: { x: 0, y: 0 }, configuration })

const MAPPING: Record<Mapping, Record<string, VariableMapping>> = {
  none: {},
  literal: { Message: { type: 'literal', literalValue: 'hello' } },
  direct: { Message: { type: 'direct', sourceOutputName: 'Text' } },
}

function caseCanvas({ depth, missing, mapping }: Spec): { nodes: WorkflowNode[]; edges: WorkflowEdge[]; expect: string[] } {
  const n1 = `${depth}-n1`
  const source = missing === 'target' ? n1 : `${depth}-ghost-source`
  const target = missing === 'source' ? n1 : `${depth}-ghost-target`
  const wire = `${depth}-dangling`
  const expect = [
    ...(missing !== 'target' ? [`edge-endpoint-unknown ${wire} source`] : []),
    ...(missing !== 'source' ? [`edge-endpoint-unknown ${wire} target`] : []),
    ...(missing === 'source' && mapping !== 'literal' ? [`required-input-unfed ${n1} Message`] : []),
  ]
  return {
    nodes: [node(n1, 'notify', missing === 'source' ? {} : { Message: 'configured' })],
    edges: [
      { id: `${depth}-start`, sourceNodeId: INPUT, targetNodeId: n1, mappings: {} },
      { id: wire, sourceNodeId: source, targetNodeId: target, mappings: MAPPING[mapping] },
    ],
    expect,
  }
}

function document(name: string, specs: Spec[]): Case {
  const deepest = Math.max(...specs.map((s) => DEPTHS.indexOf(s.depth)))
  const expect: string[] = []
  let inner: { nodes: WorkflowNode[]; edges: WorkflowEdge[] } | undefined
  for (let level = deepest; level >= 0; level--) {
    const depth = DEPTHS[level] as Depth
    const spec = specs.find((s) => s.depth === depth)
    const own = spec ? caseCanvas(spec) : { nodes: [], edges: [], expect: [] }
    expect.push(...own.expect)
    const nodes = [node(INPUT, 'WorkflowInput'), ...own.nodes]
    const edges = [...own.edges]
    if (inner) {
      const container = level === 0 ? 'loop' : 'loop2'
      nodes.push({ ...node(container, 'loop.for'), subCanvases: { Body: inner } })
      edges.push({ id: `${depth}-enter`, sourceNodeId: INPUT, targetNodeId: container, mappings: {} })
    }
    inner = { nodes, edges }
  }
  return { name, definition: inner as WorkflowDefinition, expect: expect.sort() }
}

function generate(): string {
  const cases: Case[] = []
  for (const depth of DEPTHS)
    for (const missing of MISSING)
      for (const mapping of MAPPINGS) cases.push(document(`${depth}-${missing}-missing-${mapping}`, [{ depth, missing, mapping }]))
  cases.push(document('three-canvases-at-once-a', [
    { depth: 'root', missing: 'source', mapping: 'direct' },
    { depth: 'body', missing: 'target', mapping: 'literal' },
    { depth: 'nested', missing: 'both', mapping: 'none' },
  ]))
  cases.push(document('three-canvases-at-once-b', [
    { depth: 'root', missing: 'both', mapping: 'literal' },
    { depth: 'body', missing: 'source', mapping: 'none' },
    { depth: 'nested', missing: 'source', mapping: 'direct' },
  ]))
  const file = {
    $note: [
      'Generated by packages/core/src/editor/danglingEdgeAgreement.test.ts; a mismatch writes .actual beside this file.',
      'Each case is a definition with wires naming a node absent from their canvas, at the root, in a sub-canvas and',
      'two canvases down, missing the source, the target or both, with no mapping, a literal or a wired one. `expect`',
      'lists every finding either side may make: `edge-endpoint-unknown <wire> <end>` per missing end, and',
      '`required-input-unfed <node> <input>` where the only mapping into a required input is not written at run time.',
      'The editor grades it through its store (DanglingEdgeAgreement), the compiler through Compile',
      '(DanglingEdgeAgreementTests.cs); each must find exactly the list, over the catalogue in `blocks`.',
    ],
    blocks: BLOCKS,
    cases,
  }
  return `${JSON.stringify(file, null, 2)}\n`
}

function findContracts(): string {
  for (let dir = __dirname; ; dir = dirname(dir)) {
    const candidate = join(dir, 'contracts')
    if (existsSync(join(candidate, 'workflow-validation-corpus.json'))) return candidate
    if (dirname(dir) === dir) throw new Error('contracts/ not found above ' + __dirname)
  }
}

const descriptor = (row: BlockRow): BlockTypeDescriptor => ({
  blockTypeId: row.blockTypeId,
  displayName: row.displayName,
  inputs: row.requiredStringInputs.map((name) => ({ name, displayName: name, type: 'String', isRequired: true })),
  outputs: row.stringOutputs.map((name) => ({ name, displayName: name, type: 'String', isRequired: false })),
  subCanvasNames: row.subCanvases,
  subCanvasInputs: Object.fromEntries(row.subCanvases.map((b) => [b, []])),
  subCanvasOutputs: {},
})

const DANGLING = /^Connection '([^']+)'(?: in .*)? names (source|target) node '[^']*', which does not exist on its canvas$/
const fromStructure = (finding: ValidationFinding): string => {
  const m = DANGLING.exec(finding.message)
  return m ? `edge-endpoint-unknown ${m[1]} ${m[2]}` : `unclassified: ${finding.code}`
}
const fromFinding = (f: ValidationFinding): string => f.code === 'required-input-unfed'
  ? `required-input-unfed ${f.nodeId} ${String(f.params?.portName ?? f.portName)}`
  : `unclassified: ${f.code}`

function editorFindingsPerOpenCanvas(definition: WorkflowDefinition, blocks: BlockTypeDescriptor[]): string[][] {
  const store = createWorkflowEditorStore({ portTypes: createPortTypeRegistry(BUILTIN_PORT_TYPES) })
  store.getState().setBlockTypes(blocks)
  store.getState().loadWorkflow(definition)
  const grade = () =>
    [...store.getState().validateStructureFindings().map(fromStructure), ...store.getState().validateWorkflowFindings().map(fromFinding)].sort()
  const graded = [grade()]
  for (const container of ['loop', 'loop2']) {
    if (!store.getState().nodes.some((n) => n.id === container)) break
    store.getState().enterSubCanvas(container, 'Body')
    graded.push(grade())
  }
  return graded
}

describe('dangling edge agreement, the editor', () => {
  const generated = generate()
  const path = join(findContracts(), 'dangling-edge-agreement.json')

  it('the committed file is what this generator writes', () => {
    const committed = existsSync(path) ? readFileSync(path, 'utf8') : ''
    if (committed !== generated) writeFileSync(`${path}.actual`, generated)
    expect(committed, `regenerated file written to ${path}.actual`).toBe(generated)
  })

  const file = JSON.parse(generated) as { blocks: BlockRow[]; cases: Case[] }
  const blocks = file.blocks.map(descriptor)

  it('covers every depth, missing end and mapping kind', () => {
    expect(file.cases).toHaveLength(DEPTHS.length * MISSING.length * MAPPINGS.length + 2)
  })

  it.each(file.cases.map((c) => [c.name, c] as const))('%s', (_, testCase) => {
    const graded = editorFindingsPerOpenCanvas(testCase.definition, blocks)
    graded.forEach((found, depth) => { expect(found, `with ${depth} canvases down open`).toEqual(testCase.expect) })
  })
})

describe('dangling edge agreement, every reported wire can be removed', () => {
  const file = JSON.parse(generate()) as { blocks: BlockRow[]; cases: Case[] }
  const blocks = file.blocks.map(descriptor)
  const without = (canvas: WorkflowDefinition, ids: ReadonlySet<string>): WorkflowDefinition => ({
    nodes: canvas.nodes.map((n) => (n.subCanvases
      ? { ...n, subCanvases: Object.fromEntries(Object.entries(n.subCanvases).map(([b, c]) => [b, without(c, ids)])) }
      : n)),
    edges: canvas.edges.filter((e) => !ids.has(e.id)),
  })

  it.each(file.cases.map((c) => [c.name, c] as const))('%s', (_, testCase) => {
    const dangling = new Set(testCase.expect.flatMap((k) => /^edge-endpoint-unknown (\S+)/.exec(k)?.[1] ?? []))
    for (let depth = 0; depth <= 2; depth++) {
      const store = createWorkflowEditorStore({ portTypes: createPortTypeRegistry(BUILTIN_PORT_TYPES) })
      store.getState().setBlockTypes(blocks)
      store.getState().loadWorkflow(testCase.definition)
      for (const container of ['loop', 'loop2'].slice(0, depth)) store.getState().enterSubCanvas(container, 'Body')
      if (store.getState().canvasStack.length !== depth) continue
      for (const f of store.getState().validateStructureFindings()) store.getState().removeEdge(f.edgeId ?? '', f.canvasPath)
      expect(store.getState().validateStructure()).toEqual([])
      store.getState().exitToLevel(0)
      expect(store.getState().getWorkflowDefinition()).toEqual(without(testCase.definition, dangling))
    }
  })
})
